package com.aicodingmentor.learning.dto;

import io.swagger.v3.oas.annotations.media.Schema;

import java.util.List;

@Schema(description = "Structured AI Post-Mortem counter-example breakdown")
public record PostMortemAnalysisResponse(
        @Schema(description = "Category of mistake identified", example = "OFF_BY_ONE")
        String mistakeCategory,

        @Schema(description = "High-level 1-sentence diagnostic explanation", example = "Your loop condition terminates one element early, preventing the last pair from being evaluated.")
        String conceptSummary,

        @Schema(description = "Specific counter-example input", example = "nums = [3, 2, 4], target = 6")
        String failedInput,

        @Schema(description = "Output generated by learner's logic", example = "[]")
        String actualOutput,

        @Schema(description = "Target expected output", example = "[1, 2]")
        String expectedOutput,

        @Schema(description = "Step-by-step trace of what the learner's code actually did")
        String studentFlowTrace,

        @Schema(description = "Step-by-step trace of how the invariant/correct logic reaches the expected output")
        String correctFlowTrace,

        @Schema(description = "One memorable mental rule or invariant to remember")
        String keyTakeaway,

        @Schema(description = "Related DSA concepts or tags", example = "[\"Arrays\", \"Two Pointers\", \"Loop Boundaries\"]")
        List<String> relatedConcepts
) {
}
